import { chromium } from '@playwright/test'
const b = await chromium.launch()
const ctx = await b.newContext({ storageState: 'e2e/auth-state.json', viewport: { width: 1280, height: 900 } })
const p = await ctx.newPage()
await p.goto(process.argv[2], { waitUntil: 'domcontentloaded', timeout: 180000 })
await p.waitForTimeout(15000)
console.log(p.url())
console.log((await p.locator('body').innerText()).slice(0, 1500))
await p.screenshot({ path: process.argv[3] })
await b.close()
