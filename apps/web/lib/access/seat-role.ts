/**
 * 접근권한으로 자동으로 앉는 사람의 등급 — **한 곳에만 적는다**
 *
 * `app/admin/access/actions.ts` 안에 리터럴로 박혀 있으면 값을 바꿔도 아무도 모르고,
 * 시험은 소스에서 문자열을 찾는 수밖에 없다. 그건 주석까지 통과시킨다.
 * 여기 값으로 두면 시험이 **값을 import 해서 대조**할 수 있다.
 *
 * ## 왜 MEMBER 인가 (정정 2026-09-22)
 *
 * 처음엔 READONLY 였다. 근거는 「보라고 열어 줬다」였는데, 그 결과가 아홉 명 중 여덟이
 * 보기만이었고 화면마다 「이 작업을 할 권한이 없습니다」가 떴다. 영업 CRM 은 보는 도구가
 * 아니라 쓰는 도구다. 자기 딜을 못 만들면 문을 연 것이 아니다.
 *
 * 「남의 것은 못 고치게」는 등급이 아니라 **담당자**가 가른다. 등급을 하나 더 만들면
 * 관리자가 외울 것만 늘고 경계는 여전히 안 생긴다.
 */

/** 자동으로 앉힐 때 주는 등급. 이미 자리가 있는 사람에게는 쓰지 않는다 */
export const SEAT_ROLE = 'MEMBER' as const

/**
 * 자동 경로가 절대 쓰면 안 되는 등급.
 *
 * 되돌아가는 판을 시험이 잡기 위한 목록이다. 「보기만」은 관리자가 멤버 화면에서
 * **직접 내릴 때만** 쓴다 — 자동으로 앉히는 자리에서 쓰면 문이 열린 채로 막힌다.
 */
export const SEAT_ROLE_FORBIDDEN: readonly string[] = ['READONLY']
