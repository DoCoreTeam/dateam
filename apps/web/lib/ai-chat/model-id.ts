// 모델 아이디 형식 검사 (SSOT, 순수 함수)
//
// ## 왜 SSOT 인가
//
// 같은 정규식이 두 곳에 손으로 적혀 있었다 — 서버 액션(대화 생성·모델 변경)과 스트림 라우트.
// 둘 다 `/^[\w.:\-]{1,64}$/` 였고 **둘 다 슬래시를 막았다.**
//
// ## 슬래시를 허용하는 이유 (실측 v0.7.716)
//
// Groq 은 모델 아이디에 만든 곳을 앞에 붙인다 — `openai/gpt-oss-120b`, `Qwen/qwen3.6-27b`.
// 그 모델을 고르면 **「대화 생성에 실패했습니다」** 만 뜨고 끝났다. 화면에는 고를 수 있게
// 나와 있는데 저장에서 막히니, 사용자는 무엇이 잘못됐는지 알 방법이 없다.
//
// 이 검사가 막는 것은 «이상한 문자열이 모델 자리에 들어오는 것»이지 슬래시 자체가 아니다.
// 경로 조작이 걱정이면 그건 호출부가 URL 을 만들 때 인코딩할 일이고, 여기서 할 일이 아니다.

/** 허용 문자: 영숫자·밑줄·점·콜론·하이픈·슬래시. 길이 상한은 그대로 둔다 */
export const MODEL_ID_RE = /^[\w.:/-]{1,64}$/

export function isValidModelId(m: unknown): m is string {
  return typeof m === 'string' && MODEL_ID_RE.test(m)
}
