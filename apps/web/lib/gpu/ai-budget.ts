/**
 * 한 요청 안의 AI 호출들이 예산을 **어떻게 나눠 쓰는가**.
 *
 * 왜(실측 v0.7.683): 견적서 분석은 한 요청에서 AI 를 여러 번 부른다 —
 * 전사 → 분류 → (재분류) → **본 추출** → (자가합성 재추출). 이들이 라우트 예산
 * 50초를 **먼저 오는 순서대로** 나눠 쓰다 보니, 정작 결과를 만드는 **본 추출이 꼴찌**라
 * 남는 것만 받았다. 실측 4회에서 본 추출이 받은 예산은 **6.0초 · 13.8초 · 30.9초 · 17.0초**였고
 * 전부 시간 초과로 끝났다. 앞 단계는 «있으면 좋은 것»이고 본 추출은 «없으면 기능이 없는 것»인데,
 * 굶는 쪽이 정확히 뒤바뀌어 있었다.
 *
 * 그래서 **몫을 먼저 떼어 둔다.** 앞 단계가 아무리 오래 끌어도 본 추출은 자기 몫을 받는다.
 * 앞 단계는 실패해도 화면이 계속 간다(전사는 「전사 건너뜀」, 분류는 사용자가 고른 종류로 확정).
 *
 * 계산을 라우트 밖에 두는 이유는 검증 때문이다 — 라우트 안의 식은 실브라우저 말고
 * 확인할 수단이 없다(§E-6).
 */

/** 앞 단계(전사·분류·재분류·관측) / 본 단계(추출·재추출) */
export type AiStage = 'pre' | 'main'

/** 본 추출에 반드시 남겨 두는 몫 — 앞 단계는 이 선을 넘어 쓰지 못한다. */
export const AI_MAIN_RESERVE_MS = 25_000

/** 앞 단계 하나가 쓸 수 있는 최대치 — 한 단계가 나머지를 독점하지 못하게. */
export const AI_PRE_STAGE_CAP_MS = 12_000

/** 어떤 호출에도 주는 최소치 — 0을 주면 부르자마자 실패해 이유를 못 남긴다. */
export const AI_MIN_CALL_MS = 3_000

/**
 * 이 단계에 줄 예산(ms).
 *
 * - `main`: 남은 것 전부. 마지막 주자이므로 아낄 이유가 없다.
 * - `pre` : `min(단계 상한, 남은 것 − 본 추출 몫)`. 예약분을 먼저 떼고 남는 만큼만 쓴다.
 *
 * 앞 단계가 예약분까지 밀고 들어오는 경우에도 **최소치는 준다** — 0을 주면
 * 호출이 즉시 죽어 「왜 못 했는지」조차 화면에 못 남긴다. 그 대신 그 단계는
 * 사실상 실패하고, 실패를 말하는 것은 각 단계의 폴백이 맡는다.
 */
export function aiStageBudgetMs(stage: AiStage, remainingMs: number): number {
  if (stage === 'main') return Math.max(AI_MIN_CALL_MS, Math.floor(remainingMs))
  const spare = Math.floor(remainingMs) - AI_MAIN_RESERVE_MS
  return Math.max(AI_MIN_CALL_MS, Math.min(AI_PRE_STAGE_CAP_MS, spare))
}
