/**
 * 계약 판의 말 (용어집)
 *
 * **왜 여기인가**: AI 가 만든 값에는 어느 규칙으로 만들어졌는지가 같이 저장된다.
 * 그 규칙이 바뀌면 옛 값을 새 규칙으로 올려 읽는데, **못 올리는 값**이 생긴다.
 * 그때 화면이 「데이터 오류」라고 말하면 사용자는 값이 틀렸다고 읽는다 — 값은 멀쩡하고
 * 우리가 못 올린 것뿐이다. 그래서 「이전 방식으로 만들어졌다」고 말한다.
 *
 * **판 번호를 화면에 숫자로 보이지 않는다.** 계약 3판인지 4판인지는 우리 사정이고,
 * 사용자가 할 수 있는 일이 없다. 다시 분석하면 새 방식으로 나온다는 것만 말한다.
 *
 * **금지어**: `버전 불일치` · `마이그레이션 필요` · `스키마 오류` · `레거시`
 * (전부 우리 쪽 사정을 사용자 화면에 옮겨 적은 말이다)
 */

import { iRaRa } from '../ui/josa.ts'

/** 판 번호가 붙기 전에 만들어진 값 */
export const CONTRACT_LEGACY = '이전 방식으로 만든 결과'

/** 올릴 사다리가 없어 그대로 두는 값 */
export const CONTRACT_HELD = '이전 방식 그대로 보여 드려요'

/** 지금 배포보다 새 방식으로 만들어진 값 */
export const CONTRACT_AHEAD = '더 새로운 방식으로 만든 결과'

/**
 * 왜 이렇게 보이는지 한 줄.
 *
 * 「그대로 보여 준다」를 먼저 말한다. 사용자가 가장 먼저 걱정하는 것은
 * 값이 사라졌나이지 왜 못 올렸나가 아니다.
 */
export function contractNote(kind: 'legacy' | 'gap' | 'ahead'): string {
  if (kind === 'ahead') {
    return `${CONTRACT_AHEAD}${iRaRa(CONTRACT_AHEAD)} 지금 화면이 다 해석하지 못했어요. 내용은 그대로 있습니다.`
  }
  return `${CONTRACT_LEGACY}${iRaRa(CONTRACT_LEGACY)} ${CONTRACT_HELD}. 다시 분석하면 새 방식으로 나옵니다.`
}
