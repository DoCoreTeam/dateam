/**
 * 안 잰 값의 말 — **통과·미달과 나란히 읽히는 명사 하나** (용어집 §0-2)
 *
 * ## 왜 필요한가 (사용자 지적 2026-09-28)
 *
 * 검증 화면의 상태 칸이 「아직 못 잼」이었다. 「잼」은 「재다」를 말끝에서 줄인 입말이고
 * 옆 칸의 「통과」·「미달」과 결이 다르다. 한 표 안에서 두 칸은 명사로, 한 칸은 입말로
 * 적히면 읽는 쪽은 그것이 상태 이름인지 우리가 흘린 말인지 구분할 수 없다.
 * 사용자 말 그대로: 「아직 못 잼 이런게 시스템 용어니?」
 *
 * ## 왜 한 곳인가
 *
 * 같은 뜻이 일곱 자리에 서로 다른 꼴로 흩어져 있었다 —
 * 「아직 못 잼」(관문 상태) · 「못 잼」(지연표·기간 성과) · 「못 쟀습니다」(손익) ·
 * 「아직 잴 수 없습니다」(관문 머리글) · 「잰 것 없음」(비율) · 「못 잰 항목」(화면 설명).
 * 한 자리만 고치면 나머지 여섯이 남아 화면이 섞인다. 그래서 여기서만 정한다.
 *
 * ## 「없음」이라고 안 쓰는 이유
 *
 * 「없음」은 **잰 결과가 0** 이라는 뜻으로도 읽힌다. 손익 0원과 안 잰 손익은 다른 사실이고,
 * 그 둘을 같은 말로 적으면 사람은 오늘 아무 일도 없었다고 읽고 그대로 덮는다.
 */

/** 아직 안 잰 자리에 쓰는 말. 통과·미달과 같은 자리에 오는 이름이다 */
export const NOT_MEASURED = '측정 전'

/** 값 칸이 아니라 문장 자리에 올 때 */
export const NOT_MEASURED_SENTENCE = '아직 측정할 수 없습니다'

/** 「측정 전 3건」처럼 건수를 붙일 때 */
export function notMeasuredCount(count: number, counter = '건'): string {
  return `${NOT_MEASURED} ${count}${counter}`
}

