/**
 * 웹 보강의 한계값 — 화면과 서버가 **같은 수를 본다**
 *
 * 서버(`services/enrich-web.ts`)는 DB·러너를 끌고 오므로 클라이언트가 import 할 수 없다.
 * 그렇다고 화면에 20 을 따로 적으면, 언젠가 한쪽만 바뀌어 "20곳까지"라고 안내해 놓고
 * 21곳을 보내 400 을 받는 상태가 된다. 그래서 **순수 값만** 여기 둔다.
 */

/**
 * 한 번에 보강할 수 있는 회사 수.
 *
 * 웹 검색은 회사당 실제로 돈이 나가고 수십 초가 걸린다. 상한이 없으면
 * 목록 전체를 고른 한 번의 클릭이 예산을 통째로 태우고,
 * 사용자는 그 사실을 응답이 올 때까지 모른다.
 */
export const ENRICH_BULK_MAX = 20

/**
 * 도메인으로 특정했을 때의 신뢰도 — 자동 반영 문턱(apply-policy 의 0.85) **위**.
 *
 * 도메인은 그 회사가 실제로 운영하는 주소라 동명이인 문제가 사라진다.
 * 사람이 확인해도 같은 결론이 나오는 판단이라 사람에게 물을 값어치가 없다 —
 * 물어 봐야 하는 것만 물어야 인박스를 계속 본다.
 */
export const CONFIDENCE_BY_DOMAIN = 0.9

/**
 * 이름만으로 특정했을 때 — 문턱 **아래**라 인박스로 간다.
 *
 * 같은 이름의 회사는 아주 흔하다. 이름만으로 찾은 값을 바로 채우면
 * 영업 담당자는 **다른 회사의 산업군**을 보고 제안을 준비한다.
 * 그 값은 나중에 진짜처럼 읽히고, 틀렸다는 것을 알아챌 방법이 없다.
 */
export const CONFIDENCE_BY_NAME = 0.75

/**
 * 이 보강을 얼마나 믿을지.
 *
 * 컴포넌트·서비스 밖의 순수 함수로 두는 이유: 이 한 줄이 **자동 반영이냐 인박스냐**를
 * 가른다. 서비스 안에 삼항연산으로 박아 두면 실브라우저 말고는 검증할 방법이 없고,
 * 문턱(0.85)이 움직였을 때 어긋난 사실을 아무도 모른다.
 */
export function enrichConfidence(hasDomain: boolean): number {
  return hasDomain ? CONFIDENCE_BY_DOMAIN : CONFIDENCE_BY_NAME
}
