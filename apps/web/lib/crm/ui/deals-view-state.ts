// lib/crm/ui/deals-view-state.ts — 딜 화면이 «지금 무엇을 보고 있나»를 주소에서 읽는 SSOT
//
// ## 왜 생겼나 (사용자 지적 2026-09-08)
//
// *"딜을 누르면 전체가 먼저 나와야 하는데 특정 파이프라인이 나오는게 이상해
//   그리고 뒤로가기 하면 이전 상태로 뒤로 가는거 유지하고"*
//
// 사이드바에서 「딜」을 누르면 주소는 `/crm/deals` — 파라미터가 없다.
// 그때 화면은 **기본 파이프라인 하나**를 골라 그렸다. 그래서 딜이 8건인데 3건만 보이고,
// 화면은 왜 3건인지 아무 말도 하지 않는다. 「딜」이라는 메뉴를 눌렀는데 딜의 일부가 나오는 것은
// 메뉴 이름이 약속한 것과 다르다 — **처음 오는 화면의 기본은 «전부»다.**
//
// (같은 부류의 앞선 지적: 「전체 (7개)」가 딜 수가 아니었던 것 — `pipeline-count.ts`.
//  그때는 숫자의 뜻이 갈렸고, 이번엔 **보이는 범위**가 말없이 좁혀져 있었다.)
//
// ## 왜 여기(컴포넌트 밖)에 있나
//
// 판정이 `useSearchParams()` 옆의 한 줄짜리 식이면 검증 수단이 **실브라우저뿐**이다(완료 조건 E-6).
// 이 식이 틀리면 사용자는 딜이 사라진 것처럼 본다 — 조용히 틀리는 부류라 가드가 필요하다.

/** 「전체」를 뜻하는 주소값. 빈 문자열은 «지정 안 함»과 구분이 안 돼 쓰지 않는다 */
export const ALL_PIPELINES = 'all'

/**
 * 주소의 `pipeline` 파라미터가 가리키는 파이프라인. `''` 이면 **전체**다.
 *
 * 규칙은 셋뿐이다:
 *   · 없다 → **전체**  (사이드바로 막 들어온 상태. 예전엔 여기서 기본 파이프라인을 골랐다)
 *   · `all` → 전체     (사용자가 명시적으로 고른 것 — 결과는 같지만 주소에 뜻이 남는다)
 *   · 그 밖 → 그 파이프라인
 */
export function resolvePipelineParam(param: string | null | undefined): string {
  if (!param || param === ALL_PIPELINES) return ''
  return param
}

/** 화면이 고른 파이프라인을 주소에 적을 값 — 전체는 `all` 로 적는다 */
export function pipelineParamOf(pipelineId: string): string {
  return pipelineId === '' ? ALL_PIPELINES : pipelineId
}
