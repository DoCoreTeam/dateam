-- 258_crm_quote_from_file.sql
--
-- 견적이 **어디서 왔는지**와 **아직 사람 손을 안 탔는지**를 기억할 자리.
--
-- 왜: 파일 한 장에서 견적을 여러 건 만들면, 만들어진 직후의 그것들은 전부 「읽은 그대로」다.
-- 품목 이름이 잘렸을 수도 있고 단가를 못 읽어 빈 칸일 수도 있다. 그 상태가 목록에서
-- 사람이 쓴 견적과 똑같이 보이면, 고쳐야 한다는 사실 자체가 안 보인다
-- (사용자 지시: "그건 수정전이니깐 수정 하라고 하고").
--
-- **막지 않는다. 표시만 한다.** 「수정 전이니 보내지 마세요」로 상태 전이를 잠그면,
-- 읽은 값이 이미 맞는 흔한 경우에 사람은 «고치지 않기 위해 고치는» 짓을 해야 한다.
-- 자율성은 사용자에게 있다(사용자 지시: "사용자에게 자율성을 줘 ... 그냥 편의로 할 수도 있다").
-- 그래서 이 두 칸은 어떤 게이트도 참조하지 않는다 — 배지 하나의 근거일 뿐이다.
--
-- 관계 종류(§R-1)는 해당 없음: 새 참조가 아니라 견적 자신의 속성 둘이다.
-- FK 도 트리거도 걸 것이 없다(파일은 저장하지 않으므로 가리킬 행 자체가 없다).

-- 파일에서 만들어진 시각. NULL 이면 ⓐ 파일에서 온 것이 아니거나 ⓑ 사람이 한 번 고쳐 저장했다.
-- 불리언이 아니라 시각인 이유: "언제 들어온 것인지"는 목록에서 정렬·판단에 쓰이고,
-- 해제는 NULL 한 번으로 끝나 상태가 둘 뿐이다(불리언 + 시각 두 칸이면 둘이 어긋난다).
ALTER TABLE crm_quote ADD COLUMN IF NOT EXISTS "fromFileAt" TIMESTAMPTZ;

-- 어느 파일에서 왔나. **fromFileAt 이 풀려도 남는다** —
-- 「아직 안 고쳤다」와 「이 파일에서 왔다」는 다른 사실이고, 뒤엣것은 고친 뒤에도 참이다.
-- 파일 자체는 보관하지 않으므로(§5-3) 이 이름이 출처에 대해 남는 전부다.
ALTER TABLE crm_quote ADD COLUMN IF NOT EXISTS "sourceFileName" TEXT;

COMMENT ON COLUMN crm_quote."fromFileAt" IS
  '파일에서 만들어진 시각. NULL = 파일 출처가 아니거나 사람이 한 번 고쳐 저장함. 표시 전용 — 상태 전이를 막지 않는다';
COMMENT ON COLUMN crm_quote."sourceFileName" IS
  '이 견적을 만든 파일 이름. fromFileAt 이 풀려도 남는다(출처는 고친 뒤에도 사실이다)';
