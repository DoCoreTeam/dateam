-- 244: 절사 단위에 「천만원」을 더한다
--
-- **왜**(사용자 지적 2026-09-08 · v0.7.699):
--   *"절사 버림은 백만원 단위면 백만원 단위가 없어져야지 303,000,000 이면
--     버림하고 나면 300,000,000이 되어야지"*
--
-- 「백만원 단위」는 두 가지로 읽힌다 — ⓐ 백만원의 배수로 맞춘다(지금 동작 · 303,000,000)
-- ⓑ 백만원 자리를 없앤다(300,000,000). 회계 실무의 표준은 ⓐ 이고,
-- 뜻을 ⓑ 로 바꾸면 「천원 단위」부터 넷의 의미가 한 칸씩 밀려 **이미 저장된 견적의
-- 금액이 달라진다.** 그래서 뜻은 두고 **원하는 결과를 고를 수 있게** 단위를 하나 넓힌다
-- — 천만원 단위를 고르면 300,000,000 이 된다.
--
-- 넓히기만 한다(expand). 기존 행은 건드리지 않고, 지금 쓰이는 값은 전부 그대로 통과한다.

ALTER TABLE crm_quote DROP CONSTRAINT IF EXISTS chk_rounding_unit;
ALTER TABLE crm_quote
  ADD CONSTRAINT chk_rounding_unit
  CHECK ("roundingUnit" IN (0, 1000, 10000, 100000, 1000000, 10000000));

COMMENT ON COLUMN crm_quote."roundingUnit" IS
  '절사 단위(원). 0 이면 절사하지 않는다. 총액을 이 값의 배수로 맞춘다 — 천만원이면 300,000,000 처럼 떨어진다';
