-- 274: 직인도 견적에 **굳힌다** — 271 이 로고에 한 것과 같은 벽
--
-- 왜: 설정에 직인 그림 자리를 열었다(사용자 지시 2026-09-21: 「설정에 직인파일 올리게도
--   해야지 로고처럼 · 없으면 직인생략이고」). 그런데 문서가 설정을 그대로 읽으면,
--   **오늘 직인을 한 장 올리는 순간 이미 고객에게 나간 견적서 전부에 도장이 소급해 찍힌다.**
--   고객이 든 종이와 우리 화면이 다른 말을 하면 그건 문서가 아니다 — 271 이 상호·대표이사·
--   로고에 대해 정한 것과 똑같은 이유다(사용자 지시 2026-09-20: 「그때 당시의 유지가 핵심」).
--
-- 왜 표를 새로 안 만드나
--   그림을 담는 자리는 271 이 만든 crm_quote_asset 하나면 된다. 키가 내용의 해시라
--   로고든 직인이든 같은 규칙으로 들어가고, 같은 그림을 백 번 굳혀도 행은 하나다.
--   표를 하나 더 만들면 RLS·권한·수명 규칙을 두 벌로 관리하게 된다.
--
-- 왜 백필을 안 하나
--   271 은 「그 견적이 만들어진 날의 로고」가 어디에도 없어 오늘 값을 넣었다(솔직히 적었다).
--   직인은 다르다 — **오늘까지 아무도 직인을 올린 적이 없다.** 그날 직인이 없었던 것이
--   사실이므로 NULL 이 맞고, 그 견적서는 「(직인생략)」으로 남는다. 오늘 값을 밀어 넣으면
--   없던 날인을 옛 문서에 새로 찍는 일이 된다.
--
-- 보안 (LOOP.md 7절 S1)
--   crm_quote 는 **칼럼 추가**라 기존 RLS 정책이 그대로 적용된다. 새 표가 없으므로
--   새로 켤 RLS 도 없다. 그림이 들어가는 crm_quote_asset 은 271 이 같은 판에서
--   RLS 를 켜고 anon·authenticated 권한을 회수해 두었다(서비스롤 밖에서는 못 읽고 못 쓴다).
--   담는 것은 견적서에 인쇄되어 이미 고객에게 나가던 우리 도장 그림이다.
--   올라오는 그림 자체는 앱이 assertImage 로 거른다(PNG·JPG 만, SVG 차단, 512KB 상한).
--
-- 되돌리기:
--   ALTER TABLE crm_quote DROP COLUMN IF EXISTS "sealAssetHash";

ALTER TABLE crm_quote
  ADD COLUMN IF NOT EXISTS "sealAssetHash" TEXT;

COMMENT ON COLUMN crm_quote."sealAssetHash" IS
  '그날의 직인. crm_quote_asset.hash 를 가리킨다 — 설정의 직인이 바뀌어도 이 견적서는 안 바뀐다. NULL 이면 (직인생략)';
