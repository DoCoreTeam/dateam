-- 238_ci_job_stage_signals.sql
--
-- 이슈 자동 수집(뉴스·검색 급상승·커뮤니티)을 잡 큐에 태우기 위해
-- 파이프라인 단계에 'signals' 를 **더한다**.
--
-- 왜 잡 큐인가: 웹 검색은 5~40초가 걸리고 한도(429)에 자주 막힌다.
-- 재시도·백오프·실패 큐(DLQ)·멱등키는 ci_jobs 가 이미 갖고 있다 —
-- 새 스케줄러를 만들면 그 넷을 전부 다시 짜게 된다(재사용·단일구현 정책).
--
-- 왜 파일을 나눴나: `alter type ... add value` 로 더한 값은 **같은 트랜잭션 안에서 쓸 수 없다.**
-- 컬럼·트리거와 한 파일에 두면 뒤 문장이 이 값을 참조하는 순간 통째로 롤백된다.
-- 그래서 값 추가만 여기서 끝내고, 나머지는 239 가 맡는다.

alter type ci_job_stage add value if not exists 'signals';
