-- 245: 파이프라인을 «지우지 않고 접을» 수 있게 한다
--
-- **왜 지금인가**(사용자 지적 2026-09-09: 「사업유형은 있는데 왜 저거는 없는거지?」):
-- 사업 유형은 설정 카드에서 순서를 바꾸고 숨길 수 있는데(마이그 242) 파이프라인은
-- **관리할 자리 자체가 없었다.** 그래서 안 쓰는 파이프라인을 없애는 길이 «삭제»뿐이었다.
--
-- 실측(운영 DB 2026-09-09): 파이프라인 7개 중 **5개가 딜 0건**이고, 그중 4개
-- (MSP · SI · 솔루션 · 컨설팅)는 단계 구성이 **글자까지 같은 복제본**이다.
-- 지우자니 나중에 쓸지 모르고, 두자니 딜 만들기·딜 보드·영업 단계 화면에서 계속 자리를 먹는다.
-- 리포트만 혼자 「딜 0건이면 안 쓰는 것」이라고 **추측해서** 접고 있었다
-- (`ReportsClient.tsx` — 딜이 한 건 들어오면 그 추측이 깨진다).
--
-- **추가 전용(expand)**. 칼럼 하나를 더할 뿐이고 기본값이 true 라 기존 7개는
-- 전부 지금 상태 그대로다 — 이 마이그레이션만 적용해서는 화면이 하나도 안 바뀐다(M-4).
--
-- 되돌리기:
--   ALTER TABLE crm_pipeline DROP COLUMN "isActive";

-- ── 새 딜에서 고를 수 있나 ────────────────────────────────────
-- 소프트 삭제(`deletedAt`)와 뜻이 다르다. 삭제는 «없앤다»이고 이것은 «지금은 안 쓴다»다.
-- 접힌 파이프라인도 그 파이프라인에 이미 붙은 딜은 그대로 보이고 이름도 그대로 나온다 —
-- 안 그러면 접는 순간 남의 딜이 「파이프라인 미상」이 된다.
ALTER TABLE crm_pipeline
  ADD COLUMN IF NOT EXISTS "isActive" BOOLEAN NOT NULL DEFAULT TRUE;

-- 목록을 그릴 때마다 «켜진 것 먼저 · 순서대로»로 정렬한다. 7행짜리 표에 인덱스는
-- 과하지만, 파이프라인은 딜 화면이 매번 읽는 목록이라 정렬 비용을 0으로 둔다.
CREATE INDEX IF NOT EXISTS crm_pipeline_active_position_idx
  ON crm_pipeline ("workspaceId", "isActive" DESC, position ASC);

COMMENT ON COLUMN crm_pipeline."isActive" IS
  '새 딜에서 고를 수 있나. false 면 목록 아래로 접히고 딜 만들기에서 안 보인다. 이미 이 파이프라인을 쓰는 딜은 그대로 산다.';
