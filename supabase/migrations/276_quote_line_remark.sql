-- 276: 견적 항목에 비고를 되살린다
--
-- 우리 견적서 양식에는 비고 열이 있고 실제로 쓰인다 — 실측 원본
-- 「DA견적서_한국산업기술시험원_광양분소」 2쪽에 「서버 새시」「64코어」「256GB」
-- 「Raid5」「100G-2P」「레이드컨트롤러」가 항목마다 적혀 있다.
-- 그런데 담을 칸이 없어 읽어도 버려졌다(사용자 지적 2026-09-21: 「비고는 왜 없는거야」).
--
-- 보안: 새 표가 아니라 **있는 표에 칼럼 하나**다. crm_quote_line 은 이미 RLS 가 켜져 있고
-- 정책 하나가 서 있으므로, 이 칼럼도 그 정책 아래 들어간다 — 따로 켤 것이 없다.
-- 사본(CREATE TABLE AS)을 만들지 않으므로 잠금이 떨어져 나갈 자리도 없다.
--
-- 기존 행: NULL 허용이고 기본값이 없어 한 행도 안 바뀐다. 백필하지 않는다 —
-- 비고는 사람이 적거나 원본에서 읽는 값이지 우리가 지어낼 값이 아니다.

ALTER TABLE crm_quote_line
  ADD COLUMN IF NOT EXISTS remark text;

COMMENT ON COLUMN crm_quote_line.remark IS
  '항목 비고 — 견적서 표 맨 오른쪽 열. 「서버 새시」「64코어」처럼 그 줄을 한마디로 짚는 말';
